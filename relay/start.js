'use strict';

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { createRelayServer } = require('./server.js');

const configPath = path.join(__dirname, 'relay-config.json');
let config;
if (fs.existsSync(configPath)) {
  config = JSON.parse(fs.readFileSync(configPath, 'utf8'));
} else {
  config = {
    host: '127.0.0.1',
    port: 8787,
    apiKey: 'notion-relay-' + crypto.randomBytes(24).toString('hex'),
  };
  fs.writeFileSync(configPath, JSON.stringify(config, null, 2) + '\n', { mode: 0o600 });
}

const baseUrl = `http://${config.host}:${config.port}`;
const extensionConfig = path.join(__dirname, '..', 'relay-settings.js');
const extensionSource = `// Generated by relay/start.js. Localhost-only relay credentials.\nconst NOTION_RELAY_CONFIG = Object.freeze({\n  baseUrl: ${JSON.stringify(baseUrl)},\n  apiKey: ${JSON.stringify(config.apiKey)},\n});\n`;
if (!fs.existsSync(extensionConfig) || fs.readFileSync(extensionConfig, 'utf8') !== extensionSource) {
  fs.writeFileSync(extensionConfig, extensionSource);
}

const server = createRelayServer({
  apiKey: config.apiKey,
  jobTimeoutMs: 180000,
  sessionPath: path.join(__dirname, 'notion-session.json'),
  spaceId: config.spaceId || null,
  log: (message) => console.log('[Notion API] ' + message),
});
server.listen(config.port, config.host, () => {
  console.log('[Notion relay] URL: ' + baseUrl);
  console.log('[Notion relay] Local key: ' + config.apiKey);
  console.log('[Notion relay] Waiting for the browser extension relay...');
});

function shutdown() {
  server.close(() => process.exit(0));
}
process.on('SIGINT', shutdown);
process.on('SIGTERM', shutdown);
